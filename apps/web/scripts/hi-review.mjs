// Builds docs/i18n/HI_REVIEW.md from the translation files.
// Usage: node scripts/hi-review.mjs [--check]   (--check exits 1 if the sheet is out of date)
import { readFileSync, writeFileSync } from 'node:fs'
import { resolve } from 'node:path'

const root = resolve(import.meta.dirname, '../../..')
const en = JSON.parse(readFileSync(resolve(root, 'apps/web/src/i18n/en.json'), 'utf-8'))
const hi = JSON.parse(readFileSync(resolve(root, 'apps/web/src/i18n/hi.json'), 'utf-8'))
const target = resolve(root, 'docs/i18n/HI_REVIEW.md')

function* flat(node, prefix = '') {
  for (const [key, value] of Object.entries(node)) {
    const path = prefix ? `${prefix}.${key}` : key
    if (typeof value === 'object' && value !== null) yield* flat(value, path)
    else yield [path, value]
  }
}

const hindi = Object.fromEntries(flat(hi))
const cell = (text) => String(text).replaceAll('|', '\\|')
const rows = [...flat(en)].map(([key, source]) => `| \`${key}\` | ${cell(source)} | ${cell(hindi[key] ?? '')} |  |`)

const sheet = `# Hindi string review sheet

**Status: unreviewed.** Every Hindi string below was drafted by Claude Code. None has been checked by a Hindi speaker, and none is verified for correct technical or military terminology. A human reviewer should work through this table before the pilot and fill the verdict column (Approved, Change to "...", or Query). Tracked as Q-15 in [../OPEN_QUESTIONS.md](../OPEN_QUESTIONS.md).

Source files: \`apps/web/src/i18n/en.json\` and \`apps/web/src/i18n/hi.json\`. This sheet is generated by \`npm run i18n:sheet\` in \`apps/web\` and a unit test fails when it is out of date; the reviewer's verdicts should be recorded in a copy or in the review thread, then applied to \`hi.json\`. Terms that stay in English on purpose: the product name and descriptor (from \`brand.json\`), "API", and values returned by the server such as \`demo\`.

| Key | English source | Hindi (draft) | Reviewer verdict |
|---|---|---|---|
${rows.join('\n')}

${rows.length} strings.
`

if (process.argv.includes('--check')) {
  let current = ''
  try {
    current = readFileSync(target, 'utf-8')
  } catch {
    /* missing counts as out of date */
  }
  if (current !== sheet) {
    console.error('docs/i18n/HI_REVIEW.md is out of date; run `npm run i18n:sheet` in apps/web')
    process.exit(1)
  }
} else {
  writeFileSync(target, sheet)
  console.log(`wrote ${rows.length} strings to docs/i18n/HI_REVIEW.md`)
}
